"""Render the three-reviewer adversarial peer review from stored artefacts.

Three independent reviewer voices, each given the criticism their discipline would actually
raise: transportation/OR, reinforcement learning, and statistics/experimental methodology. For
every criticism the review states the evidence already available, whether it is fatal, whether it
requires a new experiment, and the exact manuscript revision needed.

Problems are not invented to pad the review, and no experiment is proposed merely to raise a
reviewer score.

Writes ``docs/final_peer_review.md``.

    python scripts/write_peer_review.py
"""

from __future__ import annotations

try:  # `python scripts/x.py` puts scripts/ on sys.path, not the repository root
    import _path  # noqa: F401
except ModuleNotFoundError:  # imported as `scripts.x`; the root is already on sys.path
    pass

from datetime import datetime, timezone

import numpy as np
import pandas as pd
from scipy import stats

from src.common.paths import REPO_ROOT, RESULTS_DIR

from scripts.write_paper import load

DOCS = REPO_ROOT / "docs"
SCEN = ["normal", "surge", "disruption", "combined"]


def main() -> int:
    stats_art = load("statistical_analysis.json")
    power = load("power_analysis.json")
    sim = load("simulator_validation.json")
    sens = load("sensitivity_analysis.json")
    mech = load("mechanism_analysis.json")
    shap = load("shap_analysis.json")

    df = pd.read_parquet(RESULTS_DIR / "seed_level.parquet")
    reg = df[(df.variant == "main") & (df.weight_id == "w_balanced")]
    rl = reg[reg.train_seed >= 101]
    piv = rl[rl.scenario == "surge"].pivot_table(
        index="train_seed", columns="method", values="left_behind_fraction")
    diff = (piv["ppo_uq"] - piv["ppo_point"]).to_numpy(float)
    sd_real = float(diff.std(ddof=1))
    jack = max((float(stats.ttest_rel(np.delete(piv["ppo_uq"].values, i),
                                      np.delete(piv["ppo_point"].values, i)).pvalue),
                int(piv.index[i])) for i in range(len(diff)))
    rank = reg.pivot_table(index="method", columns="scenario",
                           values="left_behind_fraction", aggfunc="mean")[SCEN]
    test = next(t for t in stats_art["confirmatory"] if t["experiment_id"] == "EXP-UQ-001")
    unval = [r["quantity"] for r in sim["rows"] if r["verdict"] == "not validatable"]

    L: list[str] = []
    add = L.append

    add("# Adversarial peer review — three independent reviewers")
    add("")
    add(f"*Generated by `scripts/write_peer_review.py` at "
        f"{datetime.now(timezone.utc):%Y-%m-%dT%H:%M:%SZ} from stored artefacts. Written in the "
        "voice of hostile reviewers. No problem is invented to pad the review, and no experiment "
        "is proposed merely to raise a score.*")
    add("")
    add("**Manuscript under review:** *Controlled Evaluation of Uncertainty-Aware Reinforcement "
        "Learning for Metro Dispatch Under Stochastic Demand.* Target: transportation / "
        "operations-research venue.")
    add("")

    def criticism(number: str, title: str, body: str, evidence: str,
                  fatal: str, needs_experiment: str, revision: str) -> None:
        add(f"### {number} {title}")
        add("")
        add(body)
        add("")
        add(f"- **Evidence already available:** {evidence}")
        add(f"- **Fatal?** {fatal}")
        add(f"- **Requires a new experiment?** {needs_experiment}")
        add(f"- **Required revision:** {revision}")
        add("")

    # ------------------------------------------------------------------ reviewer 1
    add("## Reviewer 1 — Transportation / Operations Research")
    add("")
    add("**Overall:** the experimental discipline is unusual for this literature and the negative "
        "result is credible. My concerns are about what the paper can claim for practice, and "
        "whether the operational model is faithful enough to support any of it.")
    add("")

    criticism(
        "R1.1", "The proposed method loses to a threshold rule an operator could implement in an "
                "afternoon",
        "Your own Table 6 shows a tuned threshold heuristic "
        f"({rank.loc['heuristic_threshold', 'surge']:.5f}) and a static MILP "
        f"({rank.loc['milp_static', 'surge']:.5f}) beating every learned arm in every scenario, "
        f"with the proposed `ppo_uq` ({rank.loc['ppo_uq', 'surge']:.5f}) worse even than a fixed "
        f"timetable ({rank.loc['fixed_timetable', 'surge']:.5f}). What does this paper offer an "
        "operator?",
        "Fully reported in §13.1, Figure 9 and Table 6; not buried.",
        "**No** — but it is fatal to any framing as a *method* paper. As a falsification study it "
        "is a finding, not a defect.",
        "No. The comparison already exists.",
        "None outstanding. The manuscript already leads with this ranking, states that no "
        "inferential test against baselines is defined, and draws the practical implication in "
        "§18.2 that policy-learning capability rather than forecast information was the binding "
        "constraint. Retain that emphasis; resist any reviewer pressure to soften it.")

    criticism(
        "R1.2", "The endpoint depends on simulator components you did not validate",
        f"{len(unval)} of {len(sim['rows'])} quantities are not externally validated, and four of "
        "them — capacity and peak occupancy, dwell-time distribution, passenger balking and "
        "patience, and the OD distribution — are direct inputs to `left_behind_fraction`. Your "
        "validated quantities constrain the supply side, not the crowding side you measure.",
        "Table 3 and §8 state this explicitly, including which four matter.",
        "**No**, because all arms face identical conditions under common random numbers, so the "
        "*ordering* is internally valid. It is fatal to any claim about absolute magnitudes.",
        "No. Validating them would require operator data the study does not have.",
        "Already applied: §8 names the four quantities and confines every magnitude claim to "
        "ordinal comparison within the twin. Ensure no abstract or conclusion sentence quotes an "
        "absolute passenger figure as an operational prediction.")

    criticism(
        "R1.3", "Synthetic OD structure could manufacture the result",
        "The left-behind fraction depends directly on origin–destination structure, which you "
        "assume rather than measure. An OD structure that favours one dispatch pattern could "
        "produce your ordering by construction.",
        f"EXP-SENS-002 re-scores the comparison under three OD variants; `ppo_uq` is worse in "
        f"{sens['direction_agreement']['conditions_where_ppo_uq_is_worse']} of "
        f"{sens['direction_agreement']['conditions_total']} sensitivity conditions and none "
        "reverses it (§16, Figure 10, Table 7).",
        "**No.** Addressed by design.",
        "No.",
        "None. Note honestly in §16 that these variants re-score policies *trained* under the "
        "registered OD model, so they test robustness of evaluation, not of training under a "
        "different OD world — which the manuscript already says.")

    # ------------------------------------------------------------------ reviewer 2
    add("## Reviewer 2 — Reinforcement Learning / Machine Learning")
    add("")
    add("**Overall:** the placebo control is genuinely good and rare. But I am not convinced this "
        "paper is about uncertainty at all; I think it may be about an undertrained agent.")
    add("")

    criticism(
        "R2.1", "A PPO agent that cannot beat a threshold rule is undertrained, so this result is "
                "about your optimiser, not about uncertainty",
        "You froze one configuration at one budget and concluded something about uncertainty "
        "representations. With no learned arm beating a heuristic, the most parsimonious "
        "explanation is that none of your agents learned the task well, and the uncertainty arm "
        "simply had a harder optimisation problem.",
        "The manuscript concedes this in §17 Reading 2 and §19.2, and cites the divergent "
        "single-objective seed as evidence of instability. The placebo comparison partially "
        "answers it: a shuffled sigma of identical dimensionality does *not* reproduce the "
        "effect, so the gap is not pure input-capacity cost.",
        "**Not fatal to the reported claim**, which is explicitly scoped to this budget and "
        "configuration. It *is* fatal to any general claim about uncertainty-aware RL, which the "
        "paper does not make.",
        "**Yes** — a training-budget sweep is the only thing that settles it.",
        "The follow-up protocol exists (`docs/followup_training_budget_protocol.md`) with its "
        "analysis pre-committed, and was stopped incomplete "
        "(`docs/followup_status.md`, 11/80 policies, asymmetric, no evaluation cells). §20 "
        "reports it as **FOLLOW-UP / INCOMPLETE** and claims nothing from it. Keep it that way; "
        "do **not** resume it partially and report whichever budgets finish.")

    criticism(
        "R2.2", "No learning curves, so I cannot see whether anything converged",
        "You report final-policy performance only. Without training curves I cannot distinguish a "
        "converged policy that uses uncertainty badly from one that never converged.",
        "None. The registered pipeline did not log per-update returns; "
        "`results/mechanism_analysis.json` records this as unanswerable from stored artefacts.",
        "**No**, but it is a real gap in the evidence.",
        "Re-running training with logging would be a new experiment. Not permitted post hoc here.",
        "State plainly in §19 that no learning curves were stored and that convergence therefore "
        "cannot be compared across arms. Require curve logging in the follow-up protocol.")

    criticism(
        "R2.3", "The convex-loss argument is asserted at the level of the environment, not the "
                "policy's objective",
        "You show service loss is convex in arrivals and conclude a controller should hedge "
        "upward. But the agent optimises a scalarised reward including energy and cost, not "
        "service loss alone. The optimal hedging direction under *your* reward is not obviously "
        "upward.",
        "Figure 7 measures the convexity. §17 Reading 3 raises exactly this objection against the "
        "paper's own interpretation.",
        "**No**, but it weakens the interpretive claim if not handled carefully.",
        "No. A sigma-scaling probe (§20.2) would sharpen it, and is proposed rather than run.",
        "Ensure §14.3 presents the convex-loss argument as motivating a *direction of interest*, "
        "not as deriving the optimal action under the full multi-objective reward. The current "
        "OBSERVED / MECHANISM / INTERPRETATION / LIMITATION separation does this; do not let it "
        "collapse into a stronger claim during copy-editing.")

    criticism(
        "R2.4", "SHAP adds nothing and invites causal misreading",
        f"You report attributions for a single policy ({shap['method']}, seed "
        f"{shap['train_seed']}). Feature-importance orderings are seed-unstable and support no "
        "claim in the paper.",
        "The manuscript makes no causal claim from SHAP and labels it associational.",
        "**No.**",
        "No.",
        "Consider demoting the SHAP material to an appendix. It is honest but load-bearing for "
        "nothing, and its presence in the main text invites the misreading it disclaims.")

    # ------------------------------------------------------------------ reviewer 3
    add("## Reviewer 3 — Statistics / Experimental Methodology")
    add("")
    add("**Overall:** the pre-registration and the seed-level unit of analysis are handled better "
        "than most submissions I see. My concerns are about power, about what the design can and "
        "cannot test, and about one class of claim that is not licensed.")
    add("")

    criticism(
        "R3.1", "Your pilot variance estimate was wrong by a factor of two",
        f"The gate used a four-seed pilot estimating SD = {power['between_seed_sd']:.6f}; the "
        f"realised SD was {sd_real:.6f}, {sd_real / power['between_seed_sd']:.2f}× larger. Every "
        "power figure derived from the pilot is therefore optimistic, including the reported "
        "minimum detectable effect.",
        f"§11 reports both SDs and the ratio; Table 9 tabulates them.",
        "**No.** The rejection stands regardless of the planning estimate: p-values and intervals "
        "are computed from the realised data.",
        "No.",
        "Already applied. The manuscript reports both SDs, states that the planning MDE was "
        "optimistic, and — importantly — makes **no post-hoc power argument**. Verify no earlier "
        "draft language of the form *'the effect is N× the MDE, therefore conclusive'* survives "
        "anywhere; that is a fallacy independent of the arithmetic.")

    criticism(
        "R3.2", "You cannot test RL against your baselines, which is where the interesting "
                "comparison lies",
        "Baselines are deterministic and carry no training seed, so under your seed-level unit "
        "they contribute n = 1 and no paired test is defined. Given the descriptive comparison is "
        "unfavourable to your method, a sceptical reader may see a convenient gap.",
        "§13.1 states this explicitly and labels the comparison descriptive.",
        "**No**, but it limits the paper to descriptive statements about the comparison that "
        "matters most operationally.",
        "No. An evaluation-seed-paired secondary analysis (pairing on the 30 evaluation days, "
        "with the RL arm averaged over training seeds) is computable from stored data and would "
        "supply an inferential comparison.",
        "Either add that secondary analysis, clearly labelled and secondary to the registered "
        "seed-level primary, or state explicitly why it was not run. Silence here reads as "
        "avoidance.")

    criticism(
        "R3.3", "Underpowered for your own SESOI, so your nulls say nothing",
        f"Detecting the registered SESOI of {power['sesoi']} needs "
        f"n = {power['required_n_for_sesoi']} at the pilot SD and considerably more at the "
        "realised SD. Your H7 null is uninformative.",
        "§11 and §19.1 state this; H7 is reported as inconclusive, never as equivalence.",
        "**No.** Correctly handled.",
        "No.",
        "None. Confirm that no null anywhere in the manuscript, tables or dashboard is phrased as "
        "'no difference' rather than 'no difference detected'.")

    criticism(
        "R3.4", "Multiplicity across the sensitivity family",
        f"You run {sens['direction_agreement']['conditions_total']} sensitivity conditions and "
        "lean on the consistency of their sign. Consistent signs across correlated conditions are "
        "not independent evidence, and most individual conditions do not clear your BH threshold.",
        "§16 states that individual conditions mostly do not clear the threshold and that the "
        "evidence is the sign, not any single test.",
        "**No**, but the strength of the sign argument should not be overstated: these conditions "
        "re-score the *same* policies and are strongly dependent.",
        "No.",
        "Add one sentence to §16 acknowledging that the sensitivity conditions are dependent — "
        "they re-score identical policies — so consistency of sign is weaker evidence than "
        "N independent replications would be.")

    criticism(
        "R3.5", "Provenance of the stored results",
        "Almost every stored cell was produced from an uncommitted working tree, so the recorded "
        "commit does not determine the code that produced it.",
        "The manifests record `provisional: true` honestly; the reproducibility audit's "
        "`working tree clean` check inspects the tree at audit time, not at cell-production time.",
        "**No**, but it undermines a commit-level reproducibility claim.",
        "No.",
        "State in §20/reproducibility that stored results were produced from a tree ahead of the "
        "recorded commit, and re-scope the audit check to read `git_dirty` from the manifests "
        "rather than calling `git status`.")

    # ------------------------------------------------------------------ summary
    add("## Summary across reviewers")
    add("")
    add("| id | reviewer | fatal? | needs new experiment? | status |")
    add("|---|---|---|---|---|")
    rows = [
        ("R1.1", "Transport/OR", "No (fatal only to a method framing)", "No", "Reported; framing already correct"),
        ("R1.2", "Transport/OR", "No (fatal to magnitude claims)", "No", "Disclosed; magnitudes scoped"),
        ("R1.3", "Transport/OR", "No", "No", "Addressed by EXP-SENS-002"),
        ("R2.1", "RL/ML", "No (scoped claim)", "**Yes**", "Follow-up specified, incomplete"),
        ("R2.2", "RL/ML", "No", "Yes, to resolve", "Gap; must be stated"),
        ("R2.3", "RL/ML", "No", "No", "Handled by claim separation"),
        ("R2.4", "RL/ML", "No", "No", "Consider appendix"),
        ("R3.1", "Statistics", "No", "No", "Corrected and reported"),
        ("R3.2", "Statistics", "No", "No", "Secondary analysis recommended"),
        ("R3.3", "Statistics", "No", "No", "Correctly handled"),
        ("R3.4", "Statistics", "No", "No", "One sentence needed"),
        ("R3.5", "Statistics", "No", "No", "Must be stated"),
    ]
    for row in rows:
        add("| " + " | ".join(row) + " |")
    add("")
    add("**No reviewer raises a fatal objection to the reported claim.** The claim survives "
        "because it is narrow: a pre-registered, placebo-controlled result about one controller, "
        "one budget, one environment. Every fatality identified attaches to a *broader* claim the "
        "manuscript deliberately does not make.")
    add("")
    add("**The single most damaging criticism is R2.1** — that the result may be about an "
        "undertrained optimiser rather than about uncertainty. It is the only criticism requiring "
        "a new experiment, that experiment is specified and pre-registered, and it was stopped "
        "incomplete. The honest position, which the manuscript takes, is to report the confound "
        "prominently rather than to claim it away.")
    add("")
    add("### Recommendation")
    add("")
    add("**Major revision**, on the strength of R3.2 (add or justify omitting the "
        "evaluation-seed-paired baseline comparison), R2.2 and R3.5 (state the learning-curve and "
        "provenance gaps), and R3.4 (one sentence on dependence). None of these requires new "
        "computation. Acceptance would depend on a venue valuing a rigorous negative result; the "
        "paper should not be submitted anywhere expecting an algorithmic contribution.")
    add("")

    (DOCS / "final_peer_review.md").write_text("\n".join(L), encoding="utf-8")
    print(f"wrote docs/final_peer_review.md ({len(L)} lines)")
    _ = mech
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
