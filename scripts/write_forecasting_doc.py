"""Write `docs/forecasting.md`, the M4 milestone document.

`results/forecasting_report.md` is the machine record of the fit. This is the document that says
what the fit *means* for the rest of the study: whether the uncertainty channel the RL arms consume
is trustworthy, what it costs, and what it does not establish.

Every quantity is read from `results/forecasting_metrics.json` and
`results/forecasting_validation.json`. Nothing is typed.

    python scripts/write_forecasting_doc.py
"""

from __future__ import annotations

try:  # `python scripts/x.py` puts scripts/ on sys.path, not the repository root
    import _path  # noqa: F401
except ModuleNotFoundError:  # imported as `scripts.x`; the root is already on sys.path
    pass

import json
from datetime import datetime, timezone
from typing import Any

from src.common.logging import get_logger
from src.common.paths import REPO_ROOT, RESULTS_DIR

logger = get_logger(__name__)


def _load(name: str) -> dict[str, Any]:
    path = RESULTS_DIR / name
    if not path.exists():
        raise SystemExit(f"{path} is missing; run the fit and its validator first")
    return json.loads(path.read_text(encoding="utf-8"))


def main() -> int:
    manifest = _load("forecasting_metrics.json")
    if manifest.get("quick_mode") is not False:
        raise SystemExit("the stored manifest is from a quick-mode run; that is not a result")
    validation = _load("forecasting_validation.json")

    gate = manifest["gate"]
    calib = manifest["calibration"]
    quantile = manifest["metrics"]["xgb_quantile"]
    point = manifest["metrics"]["xgb_point"]
    naive = manifest["metrics"]["naive_seasonal"]

    val_prob = quantile["val"]["probabilistic"]
    test_prob = quantile["test"]["probabilistic"]

    checks = validation.get("checks", [])
    passed = sum(1 for c in checks if c.get("passed"))
    # A non-blocking failure is a warning; a blocking one stops the milestone.
    warned = [c for c in checks if not c.get("passed") and not c.get("blocking")]
    failed = [c for c in checks if not c.get("passed") and c.get("blocking")]

    lines = [
        "# Demand forecasting (M4)",
        "",
        f"Generated by `scripts/write_forecasting_doc.py` on "
        f"{datetime.now(timezone.utc).date().isoformat()} from "
        "`results/forecasting_metrics.json` and `results/forecasting_validation.json`. "
        "Every number below is read from a stored file.",
        "",
        "The machine record of the fit is `results/forecasting_report.md`; the check-by-check "
        "verification is `results/forecasting_validation.json`. This document says what the fit "
        "means for the rest of the study.",
        "",
        "## Why this milestone gates everything downstream",
        "",
        "H1 is a claim about a **calibrated** uncertainty channel. If the forecaster's intervals "
        "were miscalibrated, `ppo_uq` would be consuming a channel that misstates dispersion, and "
        "a null result could not be separated from a broken input. Protocol section 4.5 therefore "
        "makes this a blocking gate: RL training may not consume forecasts unless the quantile "
        "model beats seasonal naive on pinball loss *and* its calibrated 80% interval covers "
        "within the pre-registered band.",
        "",
        f"**Gate: {'PASSED' if gate.get('passed') else 'FAILED'}.**",
        "",
        "| condition | value | required | met |",
        "|---|---:|---|---|",
        f"| mean pinball, quantile vs seasonal naive (val) | "
        f"{gate['quantile_pinball_val']:.4f} vs {gate['naive_pinball_val']:.4f} | lower | "
        f"{gate['beats_naive_on_pinball']} |",
        f"| calibrated 80% coverage (val) | {gate['picp_80_val']:.4f} | "
        f"{gate['coverage_band'][0]}–{gate['coverage_band'][1]} | "
        f"{gate['coverage_within_band']} |",
        "",
        "## The uncertainty channel is calibrated out of sample, not just in sample",
        "",
        f"The interval-width multiplier ({calib['factor']:.3f}) is fitted on **validation only**, "
        f"moving 80% coverage from {calib['coverage_before']:.4f} to "
        f"{calib['coverage_after']:.4f} against a target of {calib['target']}. Coverage on "
        "validation is therefore in-sample with respect to that one scalar, and reporting it "
        "alone would overstate the case.",
        "",
        f"On the untouched **test** split the same multiplier gives PICP80 = "
        f"{test_prob['picp_80']:.4f} and expected calibration error "
        f"{test_prob['ece']:.4f} — better calibrated than validation "
        f"(ECE {val_prob['ece']:.4f}), on data the calibration never saw.",
        "",
        "| split | pinball | PICP80 | PICP90 | MPIW80 | MPIW80 / mean | Winkler80 | CRPS | ECE |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for split in ("val", "test"):
        block = quantile[split]["probabilistic"]
        lines.append(
            f"| {split} | {block['pinball_mean']:.4f} | {block['picp_80']:.4f} | "
            f"{block['picp_90']:.4f} | {block['mpiw_80']:.1f} | "
            f"{block['mpiw_80_normalised']:.3f} | {block['winkler_80']:.1f} | "
            f"{block['crps']:.3f} | {block['ece']:.4f} |"
        )

    lines += [
        "",
        f"**Coverage is never reported without width.** An interval reaches any coverage by "
        f"widening; the 80% interval here is {test_prob['mpiw_80_normalised']:.1%} of the mean "
        "actual value on test, so it is informative rather than vacuously wide. Winkler score "
        "penalises width and misses jointly and is reported for the same reason.",
        "",
        "## Point accuracy",
        "",
        "| model | split | MAE | RMSE | MASE | SMAPE % |",
        "|---|---|---:|---:|---:|---:|",
    ]
    for model_id, block in (("naive_seasonal", naive), ("xgb_point", point),
                            ("xgb_quantile", quantile)):
        for split in ("val", "test"):
            metrics = block[split]["point"]
            lines.append(
                f"| `{model_id}` | {split} | {metrics['mae']:.2f} | {metrics['rmse']:.2f} | "
                f"{metrics['mase']:.3f} | {metrics['smape']:.2f} |"
            )

    lines += [
        "",
        f"MASE below 1 means the model beats seasonal naive on the same horizon. The quantile "
        f"model reaches MASE {quantile['test']['point']['mase']:.3f} on test, so the arm that "
        "consumes uncertainty is not paying for it with a worse central forecast — its median is "
        f"marginally *better* than the dedicated point model's "
        f"({point['test']['point']['mase']:.3f}).",
        "",
        "SMAPE and MAPE are computed only over rows whose actual value is at least "
        f"{point['test']['point']['smape_mape_floor']}, because overnight station-hours are "
        "legitimately zero and a percentage error would otherwise be dominated by them.",
        "",
        "## What the sigma channel actually is",
        "",
        "`sigma` is derived from the calibrated interval by the frozen definition "
        "`(q90 - q10) / (2 * 1.2816)`, and validation check 4b confirms the stored column matches "
        "that formula to zero absolute deviation. It is a **dispersion estimate under a normal "
        "reference**, not a claim that demand is normally distributed. The RL arms consume it as "
        "an ordinal signal of forecast uncertainty; nothing downstream assumes normality.",
        "",
        f"Quantile crossing before the monotone repair ran at "
        f"{manifest['quantile_crossing_rate']:.2%} of adjacent quantile pairs. Independent "
        "quantile regressions cross; the repair sorts each row's quantiles, and the pre-repair "
        "rate is recorded in the manifest so the repair is visible rather than hidden. After "
        "repair the stored forecasts contain no crossings and no negative sigma.",
        "",
        "## Validation",
        "",
        f"`scripts/validate_forecasting_run.py` ran {len(checks)} checks against the stored "
        f"artefacts: **{passed} passed**, {len(warned)} warning(s), {len(failed)} failure(s).",
        "",
    ]

    if warned or failed:
        lines += ["| check | status | detail |", "|---|---|---|"]
        for check in failed + warned:
            detail = str(check.get("detail", "")).replace("|", "\\|")
            status = "**FAIL (blocking)**" if check.get("blocking") else "WARN"
            lines.append(f"| {check.get('item')} | {status} | {detail} |")
        lines.append("")

    lines += [
        "### Provenance of this run, verified by hand",
        "",
        "Check 9b compares the launch commit against the completion commit and reports two files "
        "on the forecasting code path as differing. That comparison is commit-level, and a change "
        "that was already present in the working tree at launch and committed later looks "
        "identical to one made mid-run. Both were examined:",
        "",
        f"- **`configs/forecasting.yaml`** — the only difference is `n_jobs: 4` → `10`, a thread "
        f"count. The run's manifest records `n_jobs: 10` among its selected hyperparameters, so "
        f"the run read the current value; the change was uncommitted at launch. Check 9c confirms "
        f"the configuration on disk still hashes to the value the run recorded "
        f"(`{manifest['config_hash'][:12]}`), so re-running today uses the same configuration.",
        "- **`src/data/splits.py`** — additive only: a new `regime_diagnostics` function that "
        "characterises regime instability for reporting. It is not called by split construction, "
        "and validation check 1c confirms the run's split sizes match the frozen split manifest "
        "exactly.",
        "",
        "Neither change affects the stored result. Future runs will not need this paragraph: "
        "`src/forecasting/train.py` now hashes the contents of every file it executes at launch "
        "and again at completion, and records both, so check 9b becomes an exact content "
        "comparison rather than a commit-level proxy.",
        "",
        "## What this milestone does not establish",
        "",
        "- **That the forecaster is good enough for operational use.** The gate asks whether the "
        "uncertainty channel is trustworthy enough to test a hypothesis about, not whether a "
        "transit operator should deploy it.",
        "- **That calibration holds under the surge and disruption scenarios.** Those are "
        "simulator constructions, not held-out data. Coverage is established on the historical "
        "test split only; the placebo arm exists precisely because a well-calibrated channel can "
        "still be useless to a policy.",
        "- **Anything about H1.** A calibrated forecaster is a precondition for the experiment, "
        "not evidence for its hypothesis.",
        "- **Out-of-regime transfer.** The pre-pandemic period is registered separately as "
        "EXP-ROBUST-004 (decision D-11) and is not part of this fit.",
        "",
    ]

    path = REPO_ROOT / "docs" / "forecasting.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {path.relative_to(REPO_ROOT)} ({passed}/{len(checks)} checks passed)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
