    add("## 16. Sensitivity analysis")
    add("")
    add("**OD-model sensitivity.** The origin–destination structure is synthetic and drives the "
        "primary endpoint, so the comparison was re-scored under all three OD variants. The "
        "registered direction holds in every one, against both comparators (Figure 10, Table 7). "
        "Individual conditions mostly do not clear the Benjamini–Hochberg threshold, which is "
        "expected — each uses five training seeds and ten evaluation seeds against ten and thirty "
        "in the main sweep — so the evidence is the consistent sign rather than any single test.")
    add("")
    add("**Reward-weight sensitivity is vacuous on the primary endpoint, and we report that "
        "rather than the analysis it appears to be.** Re-scoring a frozen policy under a "
        "different reward weighting changes no action, because the policy does not observe the "
        "reward at evaluation time. `left_behind_fraction` and `inductions` are therefore "
        "identical per seed across all three weightings; only `total_reward` differs. Measured "
        "there, `ppo_point` wins under every weighting, by a margin that grows as the weighting "
        "favours service — the ordering the under-dispatching mechanism predicts. Testing weight "
        "sensitivity on physical outcomes would require *retraining* under each weighting, which "
        "this design did not do.")
    add("")

    # ---------------------------------------------------------------- 17
    add("## 17. Discussion")
    add("")
    add("Three readings are consistent with the evidence, and the design separates them only "
        "partly.")
    add("")
    add("**Reading 1 — the signal is genuinely unhelpful in this setting.** The placebo "
        "comparison supports this more than a naive reading would: the calibrated sigma performed "
        "worse than a shuffled sigma with the same marginal distribution, so the harm is not the "
        "cost of two extra inputs.")
    add("")
    add("**Reading 2 — the information is usable but the optimiser did not learn to use it.** "
        "One frozen configuration trained for a fixed budget may fail to exploit an input that a "
        "longer or better-tuned run would. The convex-loss result makes this reading more "
        "plausible than it would otherwise be: theory says dispersion should motivate hedging "
        "upward, and the controller moved down, which looks more like a learning failure than an "
        "informative absence of value. That no learned arm beats a threshold heuristic points the "
        "same way.")
    add("")
    add("**Reading 3 — the scalarisation misdirects the response.** Under a weighting where "
        "energy and cost carry real weight, dispatch has an immediate certain cost while its "
        "benefit is delayed and uncertain. A policy that reads high dispersion as elevated risk "
        "may protect the certain terms and lose more on the service terms. The observed pattern — "
        "lower energy and cost, worse service, worse total reward — is consistent with this.")
    add("")
    add("Distinguishing readings 1 and 2 requires a training-budget experiment. Until it is run, "
        "the defensible statement is the narrow one: *in this setting, at this budget, the "
        "uncertainty channel hurt.*")
    add("")

    # ---------------------------------------------------------------- 18
    add("## 18. Practical implications")
    add("")
    add("These are stated conditionally, because the simulator's crowding components are not "
        "externally validated and the study covers one line.")
    add("")
    add("1. **Adding a calibrated uncertainty feature to a learned dispatch controller is not "
        "automatically beneficial**, and can degrade service. Operators evaluating such a system "
        "should require a placebo-controlled comparison rather than a before/after improvement.")
    add("2. **A tuned threshold heuristic remained the strongest method in this study.** For "
        "practitioners, the immediate implication is that policy-learning capability — not "
        "richer forecast information — was the binding constraint here.")
    add("3. **Convex service loss near capacity means the direction of a hedging response "
        "matters more than its presence.** A controller that becomes conservative under "
        "uncertainty may be worse than one that ignores uncertainty entirely.")
    add("4. **Evaluation practice.** Seed-level analysis and pre-registration changed the "
        "conclusion this study would otherwise have reached; an episode-level comparison at a "
        "single seed could plausibly have produced a favourable and unreplicable result.")
    add("")

