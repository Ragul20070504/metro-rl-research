def derived() -> dict:
    """Quantities the manuscript needs that are not stored ready-made.

    Recomputed from `results/seed_level.parquet` at render time rather than carried in prose, so
    the corrected power figures cannot drift back to the pilot-based ones they replace.
    """
    from scipy import stats as _st

    df = seed_level()
    piv = surge_pairs(df)
    diff = (piv["ppo_uq"] - piv["ppo_point"]).to_numpy(float)
    worst_p, worst_seed = jackknife(piv, "ppo_uq", "ppo_point")
    return {
        "df": df, "piv": piv, "diff": diff,
        "sd_realised": float(diff.std(ddof=1)),
        "mde_realised": mde(float(diff.std(ddof=1)), len(diff), 0.025),
        "worst_jackknife_p": worst_p, "worst_jackknife_seed": worst_seed,
        "wilcoxon_p": float(_st.wilcoxon(piv["ppo_uq"], piv["ppo_point"]).pvalue),
        "relative_pct": float(diff.mean() / piv["ppo_point"].mean() * 100),
        "seeds_favouring_point": int((diff > 0).sum()),
        "ranking": method_table(df, "left_behind_fraction")[ORDER].sort_values("surge"),
        "reward_ranking": method_table(df, "total_reward")[ORDER].sort_values(
            "surge", ascending=False),
    }


def audit_check(audit: dict, name: str) -> dict:
    for check in audit["checks"]:
        if check["name"] == name:
            return check
    return {}


